mkdir -p "$(dirname "$dest")"
tmp="$(mktemp)"
{
  echo "# generated by make prepare-compose-env; do not edit"
  for key in "${allowlist[@]}"; do
    value="$(awk -F= -v key="$key" '
      $0 ~ "^" key "=" {
        sub("^" key "=", "")
        print
        exit
      }
    ' "$src")"
    if [ -n "${value}" ]; then
      printf '%s=%s\n' "$key" "$value"
    fi
  done
} > "$tmp"

if awk -F= '
  /^[[:space:]]*#/ || NF == 0 { next }
  {
    key=$1
    if (key ~ /(TOKEN|SECRET|KEY|PASSWORD)$/) {
      print "refusing sensitive key in shared env: " key > "/dev/stderr"
      exit 1
    }
  }
' "$tmp"; then
  mv "$tmp" "$dest"
  echo "wrote $dest"
else
  rm -f "$tmp"
  exit 1
fi
