function history(seed: number, sign = 1): FundingHistoryPoint[] {
  const multipliers = [1.28, 0.72, 1.08, 0.91, 1.42, 1.15, 0.84, 1.03, 0.95, 0.76];
  return settlementTimes.map((settledAt, index) => ({
    rate:
      Number((seed * multipliers[index] * (index === 5 ? -0.2 : sign)).toFixed(6)),
    settledAt,
  }));
}

