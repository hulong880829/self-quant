export const fundingOpportunities: FundingOpportunity[] = seeds.map(
  (seed, index) => {
    const [baseAsset, quoteAsset] = seed.symbol.split("/");
    const currentRate = seed.annualized / (365 * (24 / seed.interval));

    return {
      id: `${seed.exchange.toLowerCase()}-${baseAsset.toLowerCase()}`,
      exchange: seed.exchange,
      symbol: seed.symbol,
      baseAsset,
      quoteAsset,
      positionQuantity: seed.quantity,
      positionNotional: seed.notional,
      dailyVolume: seed.volume,
      annualizedRate: seed.annualized,
      currentFundingRate: currentRate,
      nextFundingRate: seed.nextRate,
      settlementIntervalHours: seed.interval,
      nextSettlementAt: `08-05 ${seed.interval === 1 ? "15:00" : seed.interval === 4 ? "16:00" : "20:00"}`,
      settlementCountdown: seed.countdown,
      cumulative24h: seed.day,
      cumulative7d: seed.week,
      latestPrice: seed.price,
      priceChange24h: seed.priceChange,
      updatedAt: "08-05 14:02:18",
      fundingHistory: history(
        Math.max(Math.abs(seed.nextRate), 0.0025),
        seed.nextRate < 0 ? -1 : 1,
      ),
      index: {
        name: index % 3 === 0 ? "BINANCE_INDEX" : "COMPOSITE_INDEX",
        value: seed.nextRate * 0.267,
        weight: index % 3 === 0 ? 100 : 72,
      },
    };
  },
);

